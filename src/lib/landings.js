const q = (v) => `"${String(v).replace(/["\\]/g, '\\$&')}"`;

/** PostgREST `or` expression (without the parentheses) that selects this page's places. */
export function landingFilter({ match }) {
  const parts = [];
  if (match.cities?.length) parts.push(`city.in.(${match.cities.map(q).join(',')})`);
  if (match.categories?.length) parts.push(`category.in.(${match.categories.map(q).join(',')})`);
  if (match.labels?.length) {
    parts.push(`tags.ov.{${match.labels.map(q).join(',')}}`);
    for (const label of match.labels) {
      parts.push(`short_description.eq.${q(label)}`, `short_description.like.${q(`${label} ·*`)}`);
    }
  }
  return parts.join(',');
}

const labelOf = (place) => String(place.short_description || '').split(' · ')[0].trim();

/** Same rules as landingFilter, for places already in memory (sitemap counts, tests). */
export function landingMatches({ match }, place) {
  if (match.cities?.includes(place.city)) return true;
  if (match.categories?.includes(place.category)) return true;
  if (match.labels?.length) {
    const tags = place.tags || [];
    return match.labels.some((l) => tags.includes(l) || labelOf(place) === l);
  }
  return false;
}
